 for(const size of [{width:844,height:390},{width:320,height:568},{width:390,height:844}]){
  await page.setViewportSize(size);await expect(dock).toBeVisible();
  const b=await dock.boundingBox();assert(b.x>=0&&b.x+b.width<=size.width&&b.y+b.height<=size.height);
  assert.deepEqual((await saved()).project.volumes,after);
 }
 result.checks.push('Portrait, landscape and small-screen layout preserve model');
 await page.reload();await expect(page.getByTestId('viewport')).toHaveAttribute('data-rendered','true');assert.deepEqual((await saved()).project.volumes,after);
 const minimize=page.getByRole('button',{name:'Minimize conversation',exact:true});if(await minimize.isVisible())await minimize.tap();
