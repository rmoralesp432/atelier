import assert from 'node:assert/strict';
import fs from 'node:fs';
import { chromium, expect } from '@playwright/test';
const origin=process.env.ATELIER_PHONE_SMOKE_ORIGIN || 'https://atelier-emxi.onrender.com';
assert(origin==='https://atelier-emxi.onrender.com'||/^http:\/\/127\.0\.0\.1:\d+$/.test(origin));
