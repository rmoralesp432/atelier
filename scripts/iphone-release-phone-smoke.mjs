fs.mkdirSync(folder,{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const result={origin,started:new Date().toISOString(),label:process.env.ATELIER_PHONE_SMOKE_ORIGIN?'Offline calibration of production phone smoke harness; actual editable manual geometry':'Production phone smoke: actual deployed UI and manual geometry; no paid generation or physical iPhone audio',paidCalls:0,checks:[],status:'RUNNING'};
