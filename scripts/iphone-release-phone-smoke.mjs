 const orb=page.locator('.orb-large');await expect(orb).toBeVisible();
 const reflection=()=>orb.locator('.orb-reflections').evaluate(el=>getComputedStyle(el).transform);
 const first=await reflection();await expect.poll(reflection).not.toBe(first);
 result.checks.push('Live welcome orb reflections animate');
 await page.screenshot({path:folder+'/phone-welcome.png'});
 await page.evaluate(()=>localStorage.setItem('atelier.start-direct','true'));await page.reload();
